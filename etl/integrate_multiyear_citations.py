"""Build a small multi-year citation graph from extracted/matched real data.

Inputs (generated by the multi-year extractor and Parquet matcher):
  batch_citation_sections.csv
  extracted_citations.csv
  citation_parquet_match_report.csv
  citation_parquet_match_details.csv

Writes:
  data/processed/cases.jsonl
  data/processed/citation_events.jsonl

Only unique reporter-identifier matches are included. Such matches are still
candidates and are clearly marked as identifier-supported, not manually audited.
"""
from __future__ import annotations

import json
import os
import re
from datetime import date, datetime
from getpass import getpass
from pathlib import Path

import mysql.connector
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BATCH_CSV = ROOT / "batch_citation_sections.csv"
CITATIONS_CSV = ROOT / "extracted_citations.csv"
REPORT_CSV = ROOT / "citation_parquet_match_report.csv"
DETAILS_CSV = ROOT / "citation_parquet_match_details.csv"
PROCESSED = ROOT / "data" / "processed"
CASES_OUT = PROCESSED / "cases.jsonl"
EVENTS_OUT = PROCESSED / "citation_events.jsonl"


def normalize_name(value) -> str:
    value = str(value or "").lower().strip()
    value = re.sub(r"\bversus\b|\b(?:v|vs)\.?(?=\s)", " v ", value)
    value = re.sub(r"\b(?:and others|& others|ors\.?)\b", " others ", value)
    value = re.sub(r"\b(?:and another|& another|anr\.?)\b", " another ", value)
    value = re.sub(r"[^a-z0-9]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def date_string(value) -> str:
    if value is None or value == "" or (isinstance(value, float) and pd.isna(value)):
        return ""
    if isinstance(value, datetime):
        return value.date().isoformat()
    if isinstance(value, date):
        return value.isoformat()
    parsed = pd.to_datetime(value, errors="coerce")
    return "" if pd.isna(parsed) else parsed.date().isoformat()


def record_key(name, judgment_date, court_name):
    return (normalize_name(name), date_string(judgment_date), normalize_name(court_name))


def court_level(court_name) -> str:
    value = str(court_name or "").lower()
    if "supreme court" in value:
        return "Supreme Court"
    if "high court" in value:
        return "High Court"
    return "Lower Courts"


def clean(value):
    return "" if value is None or pd.isna(value) else str(value).strip()


def make_record(name, judgment_date, court_name, case_number=""):
    return {
        "case_name": clean(name),
        "judgment_date": date_string(judgment_date),
        "court_name": clean(court_name) or "Unknown Court",
        "case_number": clean(case_number),
    }


def atomic_jsonl(path: Path, records) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    with temp.open("w", encoding="utf-8") as f:
        for record in records:
            f.write(json.dumps(record, ensure_ascii=False, default=str) + "\n")
    temp.replace(path)


def main() -> None:
    for path in (BATCH_CSV, CITATIONS_CSV, REPORT_CSV, DETAILS_CSV):
        if not path.exists():
            raise FileNotFoundError(f"Required input missing: {path}")

    batch = pd.read_csv(BATCH_CSV, dtype=str).fillna("")
    citations = pd.read_csv(CITATIONS_CSV, dtype=str).fillna("")
    report = pd.read_csv(REPORT_CSV, dtype=str).fillna("")
    details = pd.read_csv(DETAILS_CSV, dtype=str).fillna("")

    required_batch = {"case_title", "decision_date", "court_name"}
    required_citations = {"source_case_title", "source_judgment_date", "source_court_name", "raw_citation_text"}
    required_report = {"parquet_identifier_match_records"}
    required_details = {"candidate_row", "match_type", "case_title", "decision_date", "court_name"}
    for name, frame, required in [
        ("batch file", batch, required_batch),
        ("citation file", citations, required_citations),
        ("match report", report, required_report),
        ("match details", details, required_details),
    ]:
        missing = required - set(frame.columns)
        if missing:
            raise ValueError(f"{name} is missing required columns: {sorted(missing)}")

    source_records: dict[tuple, dict] = {}
    for _, row in batch.iterrows():
        rec = make_record(
            row.get("case_title"), row.get("decision_date"),
            row.get("court_name"), row.get("docket_number", ""),
        )
        if rec["case_name"] and rec["judgment_date"]:
            source_records.setdefault(
                record_key(rec["case_name"], rec["judgment_date"], rec["court_name"]), rec
            )
    if not source_records:
        raise RuntimeError("No source judgments have both title and decision date.")

    # A candidate is eligible only when the scan found exactly one row by reporter identifier.
    report_by_row = {idx + 1: row for idx, (_, row) in enumerate(report.iterrows())}
    details_by_row: dict[int, pd.DataFrame] = {}
    if not details.empty:
        details["candidate_row_num"] = pd.to_numeric(details["candidate_row"], errors="coerce")
        for candidate_row, group in details.groupby("candidate_row_num", dropna=True):
            details_by_row[int(candidate_row)] = group

    target_by_row: dict[int, dict] = {}
    skip_ambiguous = 0
    for candidate_row, report_row in report_by_row.items():
        try:
            identifier_count = int(float(report_row.get("parquet_identifier_match_records", "0") or 0))
        except (TypeError, ValueError):
            identifier_count = 0
        if identifier_count != 1:
            continue
        group = details_by_row.get(candidate_row)
        if group is None or group.empty:
            continue
        if "match_type" not in group.columns:
            continue
        group = group[group["match_type"].astype(str).str.contains("IDENTIFIER", case=False, na=False)]
        if group.empty:
            continue
        # Details can repeat a target if it matched both identifier and name; count unique target identities.
        unique_targets = group.drop_duplicates(subset=["case_title", "decision_date", "court_name"])
        if len(unique_targets) != 1:
            skip_ambiguous += 1
            continue
        target_row = unique_targets.iloc[0]
        rec = make_record(
            target_row.get("case_title"), target_row.get("decision_date"),
            target_row.get("court_name"), target_row.get("docket_number", ""),
        )
        if not rec["case_name"] or not rec["judgment_date"]:
            continue
        rec["_raw_citation_text"] = clean(citations.iloc[candidate_row - 1].get("raw_citation_text")) if candidate_row <= len(citations) else ""
        rec["_citation_identifiers"] = clean(citations.iloc[candidate_row - 1].get("citation_identifiers")) if candidate_row <= len(citations) else ""
        rec["_match_basis"] = "unique_reporter_identifier_match_needs_audit"
        target_by_row[candidate_row] = rec

    records_by_key: dict[tuple, dict] = dict(source_records)
    for target in target_by_row.values():
        key = record_key(target["case_name"], target["judgment_date"], target["court_name"])
        records_by_key.setdefault(key, {k: v for k, v in target.items() if not k.startswith("_")})

    # MySQL credentials are read from environment/.env; never print secrets.
    try:
        from dotenv import load_dotenv
        load_dotenv(ROOT / ".env")
    except ImportError:
        pass
    password = os.getenv("MYSQL_PASSWORD") or getpass("MySQL root password: ")
    connection = mysql.connector.connect(
        host=os.getenv("MYSQL_HOST", "127.0.0.1"),
        port=int(os.getenv("MYSQL_PORT", "3306")),
        user=os.getenv("MYSQL_USER", "root"),
        password=password,
        database=os.getenv("MYSQL_DATABASE", "legal_citation_analyzer"),
    )

    inserted_cases = 0
    inserted_courts = 0
    events: list[dict] = []
    skipped_events = 0
    try:
        cursor = connection.cursor()
        cursor.execute("SELECT court_id, court_name FROM COURT")
        court_cache = {normalize_name(name): int(cid) for cid, name in cursor.fetchall()}

        for rec in records_by_key.values():
            ck = normalize_name(rec["court_name"])
            if ck and ck not in court_cache:
                level = court_level(rec["court_name"])
                cursor.execute(
                    "INSERT INTO COURT (court_name, location, court_level) VALUES (%s, %s, %s)",
                    (rec["court_name"], None, level),
                )
                court_cache[ck] = int(cursor.lastrowid)
                inserted_courts += 1

        cursor.execute("""
            SELECT lc.case_id, lc.case_name, lc.case_number, lc.judgment_date, c.court_name
            FROM LEGAL_CASE lc LEFT JOIN COURT c ON c.court_id = lc.court_id
        """)
        existing = {}
        for case_id, case_name, case_number, judgment_date, court_name in cursor.fetchall():
            key = record_key(case_name, judgment_date, court_name or "")
            existing.setdefault(key, int(case_id))

        case_id_by_key = {}
        for key, rec in records_by_key.items():
            if key in existing:
                case_id_by_key[key] = existing[key]
                continue
            court_id = court_cache.get(normalize_name(rec["court_name"]))
            cursor.execute(
                "INSERT INTO LEGAL_CASE (case_name, case_number, judgment_date, court_id) VALUES (%s, %s, %s, %s)",
                (rec["case_name"], rec.get("case_number", "")[:255] or None, rec["judgment_date"], court_id),
            )
            case_id_by_key[key] = int(cursor.lastrowid)
            existing[key] = int(cursor.lastrowid)
            inserted_cases += 1

        # Link each citation candidate to its source judgment using title + date + court.
        seen_pairs = set()
        for idx, citation in citations.iterrows():
            candidate_row = idx + 1
            target = target_by_row.get(candidate_row)
            if not target:
                continue
            source_key = record_key(
                citation.get("source_case_title"),
                citation.get("source_judgment_date"),
                citation.get("source_court_name") or "Unknown Court",
            )
            target_key = record_key(target["case_name"], target["judgment_date"], target["court_name"])
            citing_id = case_id_by_key.get(source_key)
            cited_id = case_id_by_key.get(target_key)
            citation_date = date_string(citation.get("source_judgment_date"))
            if not citing_id or not cited_id or not citation_date or citing_id == cited_id or (citing_id, cited_id) in seen_pairs:
                skipped_events += 1
                continue
            events.append({
                "citing_case_id": citing_id,
                "cited_case_id": cited_id,
                "citation_date": citation_date,
                "year": int(citation_date[:4]),
                "citing_court_level": court_level(citation.get("source_court_name", "")),
                "raw_citation_text": clean(citation.get("raw_citation_text")),
                "citation_identifiers": clean(citation.get("citation_identifiers")),
                "match_basis": "unique_reporter_identifier_match_needs_audit",
            })
            seen_pairs.add((citing_id, cited_id))

        connection.commit()

        # Export catalog including all valid MySQL cases so MongoDB can resolve event IDs.
        cursor.execute("""
            SELECT lc.case_id, lc.case_name, lc.case_number, lc.judgment_date, c.court_name
            FROM LEGAL_CASE lc LEFT JOIN COURT c ON c.court_id = lc.court_id
            WHERE lc.case_name IS NOT NULL AND TRIM(lc.case_name) <> '' AND lc.judgment_date IS NOT NULL
            ORDER BY lc.case_id
        """)
        catalog = []
        for case_id, name, case_number, judgment_date, court_name in cursor.fetchall():
            catalog.append({
                "case_id": int(case_id),
                "case_name": name,
                "case_number": case_number,
                "judgment_date": date_string(judgment_date),
                "court_name": court_name or "Unknown Court",
            })
        atomic_jsonl(CASES_OUT, catalog)
        atomic_jsonl(EVENTS_OUT, events)
        cursor.close()

        print("\n===== MULTI-YEAR CITATION INTEGRATION SUMMARY =====")
        print("Source judgments identified:", len(source_records))
        print("Unique identifier-supported target candidates:", len(target_by_row))
        print("New court rows inserted:", inserted_courts)
        print("New LEGAL_CASE rows inserted:", inserted_cases)
        print("Citation events exported:", len(events))
        print("Candidate rows skipped as ambiguous/unusable:", skip_ambiguous)
        print("Events skipped for missing source/target, self-edge or duplicate:", skipped_events)
        if events:
            print("Events by citation year:")
            print(pd.DataFrame(events).groupby("year").size().to_string())
        print("Catalog exported:", len(catalog), "cases ->", CASES_OUT)
        print("Events JSONL ->", EVENTS_OUT)
        print("Note: edges are identifier-supported candidates, not manually audited legal conclusions.")
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


if __name__ == "__main__":
    main()
